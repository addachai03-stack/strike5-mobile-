import { readFileSync, existsSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import vm from 'node:vm';
const html=readFileSync('index.html','utf8');
const match=html.match(/<script>\s*([\s\S]*?)\s*<\/script>/);
assert.ok(match,'Inline game JS not found');
new vm.Script(match[1]);
const char=match[1].match(/const CHARACTERS=\[([\s\S]*?)\];/);
const guns=match[1].match(/const WEAPONS=\[([\s\S]*?)\];/);
assert.ok(char && guns,'Roster and weapons missing');
assert.equal((char[1].match(/\{id:'/g)||[]).length,12);
assert.equal((guns[1].match(/\{id:'/g)||[]).length,17);
assert.ok(html.includes('<script src="./vendor/babylon.js"></script>'),'Offline engine path missing');
assert.ok(html.includes('id="sensitivityRange"')&&html.includes('id="killCounter"'));
for(const file of ['preview.js','preview.css','lobby.js','lobby.css','manifest.webmanifest','sw.js','icon.svg','capacitor.config.json','scripts/build-web.mjs']) assert.ok(existsSync(file),file+' missing');
assert.ok(html.includes('id="homePlay"')&&html.includes('id="lobbyStart"')&&html.includes('id="lobbyHome"'));
const lobbyJS=readFileSync('lobby.js','utf8');
new vm.Script(lobbyJS);
assert.ok(lobbyJS.includes("start.click()") && lobbyJS.includes("show('home')"));
const sw=readFileSync('sw.js','utf8');
assert.ok(sw.includes('lobby.js')&&sw.includes('lobby.css'));
console.log('PASS: homepage/lobby JS + navigation hooks and PWA cache');
assert.ok(html.includes('id="inspectCanvas"')&&html.includes('id="inspectWeapon"')&&html.includes('id="inspectOperator"'),'Inspector controls missing');
assert.ok(html.includes('STRIKE5ReadOnly')&&html.includes('strike5:loadout'),'Game-to-inspector integration missing');
const preview=readFileSync('preview.js','utf8');
new vm.Script(preview);
assert.ok(preview.includes('draw3d')&&preview.includes('render2d'),'3D + fallback renderer missing');
const cache=readFileSync('sw.js','utf8');
assert.ok(cache.includes('preview.js')&&cache.includes('preview.css'),'Inspector not cached for offline PWA');
assert.ok(preview.includes('function fabric('),'procedural cloth texture missing');
assert.ok(preview.includes('animatedParts')&&preview.includes('helmet rail'),'operator equipment/idle animation missing');
assert.ok(match[1].includes('function animateCombatVisuals('),'frame-level bot animation missing');
assert.ok(match[1].includes('botMuzzleGlow')&&match[1].includes('gunRoot.position.y+='),'bot flash/viewmodel animation missing');
console.log('PASS: V7 tactical gear, camo texture and combat animation code');
console.log('PASS: V6 3D/2D inspector syntax, UI hooks, offline bundled files');
console.log('PASS: JS syntax, 12 characters, 17 weapons, sensitivity, K/D HUD, local engine path');
